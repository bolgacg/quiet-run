using System.Text.Json;
using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace QuietRun.Cli;

/// <summary>Turns a dotnet test TRX file into the list of tests and outcomes the page shows.</summary>
public static class TestList
{
    private static readonly string[] Order =
        ["LeakTests", "ClogTests", "AirTests", "QuietTests", "DriftTests", "HealthyTests", "TimingTests", "CompositionTests",
         "WindowTests", "EnvelopeTests", "CsvAndSimulatorTests"];

    public static int Run(string trxPath, string outPath)
    {
        var doc = XDocument.Load(trxPath);
        XNamespace ns = doc.Root!.Name.Namespace;
        var results = doc.Descendants(ns + "UnitTestResult")
            .Select(r => (Name: (string)r.Attribute("testName")!, Outcome: (string)r.Attribute("outcome")!))
            .ToList();
        if (results.Count == 0) throw new ArgumentException($"{trxPath}: no test results found.");

        var tests = results.Select(r =>
            {
                var m = Regex.Match(r.Name, @"^(?:.*\.)?(?<cls>\w+Tests)\.(?<name>[^(]+)(?:\((?<args>.*)\))?$");
                string cls = m.Success ? m.Groups["cls"].Value : "Other";
                string name = m.Success ? m.Groups["name"].Value.Replace('_', ' ') : r.Name;
                if (m.Success && m.Groups["args"].Success)
                    name += $" ({Regex.Replace(m.Groups["args"].Value, @"\w+: ""?([^""]*)""?", "$1")})";
                return new { cls, name, outcome = r.Outcome };
            })
            .OrderBy(t => Array.IndexOf(Order, t.cls) is var i && i < 0 ? 99 : i)
            .ThenBy(t => t.name, StringComparer.Ordinal)
            .ToList();

        var payload = new
        {
            total = tests.Count,
            passed = tests.Count(t => t.outcome == "Passed"),
            failed = tests.Count(t => t.outcome == "Failed"),
            tests,
        };
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outPath))!);
        File.WriteAllText(outPath,
            "// Generated by `quiet-run tests` from the dotnet test results. Do not edit by hand.\n" +
            "window.QR_TESTS = " + JsonSerializer.Serialize(payload) + ";\n");
        Console.WriteLine($"wrote {outPath}: {payload.passed} of {payload.total} passed");
        return payload.failed == 0 ? 0 : 4;
    }
}
